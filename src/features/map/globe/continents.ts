/**
 * Hand-simplified, deliberately blobby landmasses as [lon, lat] outlines.
 * Accuracy doesn't matter: each shape only needs to read at a glance on a cartoon globe.
 * The texture painter smooths every outline with quadratic curves, so corners come out soft.
 */

export type LonLat = readonly [lon: number, lat: number];

export interface Landmass {
  id: string;
  points: readonly LonLat[];
  /** Grow the shape around its centre (tiny islands read better a bit chunkier). */
  inflate?: number;
  /**
   * Polar cap: the outline is the coast only. The painter closes it along the bottom edge of
   * the texture and inks just the coast, so no seam shows at the pole.
   */
  cap?: 'south';
}

